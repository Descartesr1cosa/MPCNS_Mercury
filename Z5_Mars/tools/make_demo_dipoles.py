#!/usr/bin/env python3
"""Generate a deterministic CT test fixture, NOT an observational Mars model."""
import argparse
import math
from pathlib import Path


def generate(count):
    if count <= 0:
        raise ValueError('count must be positive')
    radius = 3.396e6 - 20e3
    volume = 4 * math.pi * radius**2 * 40e3 / count
    golden = math.pi * (3 - math.sqrt(5))
    yield '# SYNTHETIC numerical demonstration; NOT Langlais observational coefficients.\n'
    yield '# See docs/mars/MarsCrustalDipoles.md; generated by tools/make_demo_dipoles.py.\n'
    yield '# Cartesian simulation frame; x y z [m], mx my mz [A m^2], core [m].\n'
    yield f'MARS_DIPOLES_V1 {count}\n'
    for i in range(count):
        z = 1 - 2 * (i + 0.5) / count
        lon = i * golden
        lat = math.asin(z)
        rxy = math.sqrt(1 - z*z)
        unit = (rxy * math.cos(lon), rxy * math.sin(lon), z)
        # Artificial southern banded magnetization; completely specified here.
        strength = 2 * math.exp(-((lat + math.pi/4) / 0.45)**2) * math.sin(8 * lon)
        moment = volume * strength
        values = [radius * x for x in unit] + [moment * x for x in unit] + [0.0]
        yield ' '.join(f'{x:.16e}' for x in values) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('--count', type=int, default=4840)
    args = parser.parse_args()
    args.output.write_text(''.join(generate(args.count)), encoding='utf-8')
